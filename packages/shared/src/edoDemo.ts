export function edoSignals(now: Date): ModuleSignal[] {
  const data = buildEdoData(now);
  return [
    {
      moduleKey: 'edo',
      label: 'Imzo kutmoqda',
      count: data.documents.filter((d) => d.status === 'SIGN').length,
      tone: 'warning',
      url: 'module://edo/documents',
    },
    {
      moduleKey: 'edo',
      label: 'Muddati oʻtgan',
      count: data.control.counters.overdue,
      tone: 'danger',
      url: 'module://edo/control',
    },
  ];
}
